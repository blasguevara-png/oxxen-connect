-- Generic entity id keeps order auditing queryable without weakening the existing card audit schema.
alter table public.oxxen_connect_audit_logs add column if not exists entity_id uuid;
create index if not exists idx_oxxen_connect_audit_entity_created
  on public.oxxen_connect_audit_logs(entity_type, entity_id, created_at desc);

create or replace function public.oxxen_connect_audit_order_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_action text;
begin
  if tg_op = 'INSERT' then
    insert into public.oxxen_connect_audit_logs(admin_id, action, entity_type, entity_id, old_value, new_value, metadata)
    values (auth.uid(), 'order.created', 'order', new.id, null, to_jsonb(new), jsonb_build_object('order_code', new.order_code));
    return new;
  end if;

  if old.status is distinct from new.status then
    v_action := case new.status
      when 'confirmed' then 'order.confirmed'
      when 'in_production' then 'order.production_started'
      when 'ready' then 'order.ready'
      when 'delivered' then 'order.delivered'
      when 'cancelled' then 'order.cancelled'
      else 'order.updated' end;
  elsif old.payment_status is distinct from new.payment_status then
    v_action := 'order.payment_status_changed';
  elsif old.customer_id is distinct from new.customer_id
     or old.discount is distinct from new.discount
     or old.notes is distinct from new.notes then
    v_action := 'order.updated';
  else
    return new;
  end if;

  insert into public.oxxen_connect_audit_logs(admin_id, action, entity_type, entity_id, old_value, new_value, metadata)
  values (auth.uid(), v_action, 'order', new.id, to_jsonb(old), to_jsonb(new), jsonb_build_object('order_code', new.order_code));
  return new;
end;
$$;
revoke all on function public.oxxen_connect_audit_order_change() from public, anon, authenticated;

drop trigger if exists trg_oxxen_connect_audit_order_change on public.oxxen_connect_orders;
create trigger trg_oxxen_connect_audit_order_change
after insert or update on public.oxxen_connect_orders
for each row execute function public.oxxen_connect_audit_order_change();

create or replace function public.oxxen_connect_audit_order_item_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_action text := 'order_item.updated';
begin
  if tg_op = 'INSERT' then v_action := 'order_item.created';
  elsif old.card_id is distinct from new.card_id then v_action := 'order_item.card_assigned';
  end if;

  insert into public.oxxen_connect_audit_logs(admin_id, card_id, action, entity_type, entity_id, old_value, new_value, metadata)
  values (
    auth.uid(),
    new.card_id,
    v_action,
    'order_item',
    new.id,
    case when tg_op = 'INSERT' then null else to_jsonb(old) end,
    to_jsonb(new),
    jsonb_build_object('order_id', new.order_id)
  );
  return new;
end;
$$;
revoke all on function public.oxxen_connect_audit_order_item_change() from public, anon, authenticated;

drop trigger if exists trg_oxxen_connect_audit_order_item_change on public.oxxen_connect_order_items;
create trigger trg_oxxen_connect_audit_order_item_change
after insert or update on public.oxxen_connect_order_items
for each row execute function public.oxxen_connect_audit_order_item_change();

